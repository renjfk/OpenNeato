#!/usr/bin/env python3
"""Generate a firmware signing key pair and the matching public-key header.

Usage:
    ./scripts/ota_keygen.py --out-key ~/ota-signing-key.pem --release \
        --out-header firmware/src/ota_public_keys.h

The private key stays offline (GitHub Actions secret OTA_SIGNING_KEY); the header
is committed so firmware can verify signed update tokens.

The header holds up to two keys so a key can be rotated. The release workflow
generates it from the secret plus an optional rotation key
(vars.OTA_ROTATION_PUBLIC_KEY) and always writes it with --release.
"""

import argparse
import os
import re
import subprocess
import sys

HEADER_TEMPLATE = """#ifndef OTA_PUBLIC_KEYS_H
#define OTA_PUBLIC_KEYS_H

#include <stdint.h>

// ECDSA P-256 public keys trusted to sign OpenNeato firmware releases.
//
// Each key is the uncompressed SEC1 point (0x04 || X || Y, 65 bytes). Up to
// OTA_PUBLIC_KEY_MAX keys are accepted, so a key rotation can ship a new key in
// one release and drop the old one in the next.
//
// OTA_KEYS_ARE_RELEASE is 1 only for builds produced by the release pipeline.
// Development builds keep it 0 so the UI does not offer installs the device
// cannot verify.
//
// Generated by scripts/ota_keygen.py. Never edit by hand.

#define OTA_KEYS_ARE_RELEASE {release}

#define OTA_PUBLIC_KEY_MAX {count}

static const uint8_t OTA_PUBLIC_KEYS[OTA_PUBLIC_KEY_MAX][65] = {{
{keys}
}};

#endif // OTA_PUBLIC_KEYS_H
"""

MAX_KEYS = 2
KEY_BYTES = 65
KEY_PATTERN = re.compile(r"0x([0-9a-fA-F]{2})")


def run(*args):
    return subprocess.run(args, check=True, capture_output=True).stdout


def public_key_hex(private_key_path):
    # openssl prints the EC public key as a DER SubjectPublicKeyInfo; the last 65
    # bytes of it are the uncompressed point the firmware expects.
    der = run("openssl", "pkey", "-in", private_key_path, "-pubout", "-outform", "DER")
    point = der[-KEY_BYTES:]
    if point[0] != 0x04:
        sys.exit("error: unexpected public key encoding (not an uncompressed EC point)")
    return point.hex()


def validate_key_hex(value, origin):
    value = value.strip().lower()
    if len(value) != KEY_BYTES * 2 or not all(c in "0123456789abcdef" for c in value):
        sys.exit(f"error: {origin} is not a 65-byte hex EC public key")
    if not value.startswith("04"):
        sys.exit(f"error: {origin} is not an uncompressed EC public key (no 0x04 prefix)")
    return value


def existing_keys(header_path):
    """Read the keys already in a generated header, in order."""
    if not os.path.exists(header_path):
        return []
    text = open(header_path).read()
    if "OTA_PUBLIC_KEYS" not in text:
        return []
    body = text.split("OTA_PUBLIC_KEYS[OTA_PUBLIC_KEY_MAX][65]", 1)[1]
    keys = []
    for block in re.findall(r"\{([^{}]*)\}", body):
        values = KEY_PATTERN.findall(block)
        if len(values) != KEY_BYTES:
            continue
        key = "".join(values).lower()
        if key.startswith("04") and key != "04" + "00" * (KEY_BYTES - 1):
            keys.append(key)
    return keys


def format_key(hex_point):
    values = [f"0x{hex_point[i:i + 2]}" for i in range(0, len(hex_point), 2)]
    lines = ["        " + ", ".join(values[i:i + 17]) + "," for i in range(0, len(values), 17)]
    return "        {" + "\n".join(line.strip() for line in lines) + "}"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-key", help="write a new private key here (omit to only rewrite the header)")
    parser.add_argument("--out-header", default="firmware/src/ota_public_keys.h")
    parser.add_argument("--key", help="existing private key to embed")
    parser.add_argument(
        "--extra-key",
        action="append",
        default=[],
        help="extra public key (65-byte hex) to trust, e.g. the next key during a rotation",
    )
    parser.add_argument(
        "--rotate",
        action="store_true",
        help="keep the keys already in the header and add the new one",
    )
    parser.add_argument("--slot", type=int, choices=[0, 1], default=0, help="slot to replace with --rotate")
    parser.add_argument(
        "--release",
        action="store_true",
        help="mark the header as release-pipeline output (enables signed updates in the UI)",
    )
    args = parser.parse_args()

    if args.out_key and not os.path.exists(args.out_key):
        run("openssl", "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", args.out_key)
        os.chmod(args.out_key, 0o600)

    source = args.out_key or args.key
    if not source:
        sys.exit("error: pass --out-key to create a key or --key to embed an existing one")

    primary = public_key_hex(source)

    if args.rotate:
        keys = existing_keys(args.out_header)
        while len(keys) < MAX_KEYS:
            keys.append("")
        keys[args.slot] = primary
    else:
        keys = [primary]

    for extra in args.extra_key:
        extra = validate_key_hex(extra, "--extra-key")
        if extra not in keys:
            keys.append(extra)

    keys = [key for key in keys if key][:MAX_KEYS]
    body = ",\n".join(format_key(key) for key in keys)
    with open(args.out_header, "w") as handle:
        handle.write(HEADER_TEMPLATE.format(release=1 if args.release else 0, count=len(keys), keys=body))

    print(f"wrote {args.out_header} ({len(keys)} key{'s' if len(keys) > 1 else ''}, release={1 if args.release else 0})")
    for key in keys:
        print(f"public key: {key}")


if __name__ == "__main__":
    main()
